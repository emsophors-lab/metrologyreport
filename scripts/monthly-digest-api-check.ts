import assert from 'node:assert/strict';
const base = process.env.MLRS_BASE || 'http://localhost:3004';
if (!['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname)) throw new Error('Local digest check refuses remote hosts');
const staff = { 'X-NMC-User-ID': 'user-sa-001', 'X-NMC-Username': 'superadmin', 'X-NMC-User-Role': 'superadmin' };
const company = { 'X-NMC-User-ID': 'user-co-001', 'X-NMC-Username': 'company01', 'X-NMC-User-Role': 'company' };
const settingsPath = '/api/monthly-report-digest/settings';
assert.equal((await fetch(base + settingsPath)).status, 401);
assert.equal((await fetch(base + settingsPath, { headers: company })).status, 403);
assert.equal((await fetch(base + '/api/monthly-report-digest')).status, 401);
assert.equal((await fetch(base + '/api/monthly-report-digest?secret=not-a-real-secret')).status, 401);
assert.equal((await fetch(base + '/api/monthly-report-digest?dry_run=1', { method: 'POST', headers: company })).status, 401);
const beforeResponse = await fetch(base + settingsPath, { headers: staff });
assert.equal(beforeResponse.status, 200);
const before = await beforeResponse.json();
assert.equal(before.schedule.hour, 8);
assert.equal(before.schedule.day, 8);
assert.equal(before.schedule.timezone, 'Asia/Phnom_Penh');
assert.equal(typeof before.cron_secret_configured, 'boolean');
if (before.bot) assert.deepEqual(Object.keys(before.bot).sort(), ['group_chat_id', 'id', 'name', 'token_configured', 'username']);
const previewResponse = await fetch(base + '/api/monthly-report-digest?dry_run=1&period=2026-04', { method: 'POST', headers: staff });
const preview = await previewResponse.json();
assert.equal(previewResponse.status, 200, JSON.stringify(preview));
assert.equal(preview.status, 'DryRun');
assert.equal(preview.period, '2026-04');
assert.equal(preview.submitted + preview.missing, preview.licensees);
assert.ok(preview.messages.length > 0);
assert.equal((await fetch(base + '/api/monthly-report-digest?dry_run=1&period=2026-13', { method: 'POST', headers: staff })).status, 400);
const after = await (await fetch(base + settingsPath, { headers: staff })).json();
assert.deepEqual(after.logs, before.logs, 'Preview must not create delivery log records');
console.log('PASS: local digest settings staff-only, no secrets, GET cron protection, company rejected, read-only real-data preview, invalid period rejected, delivery log unchanged. No Telegram send was requested.');
